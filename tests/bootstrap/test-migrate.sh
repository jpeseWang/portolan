#!/usr/bin/env bash
# shellcheck source=tests/bootstrap/_lib.sh
. "$(dirname "$0")/_lib.sh"

make_src v2.0.0
MARK='# solo-dev-workflow:generated'

# Project 1: a git repo where v1 ran with --local over a tracked CLAUDE.md.
P="$tmp/client repo"
mkdir -p "$P/.claude/commands/_shared" "$P/.claude/skills/mine" "$P/.claude/hooks" "$P/.claude/tools"
(cd "$P" && git init -q . && printf 'TEAM RULES\n' > CLAUDE.md && printf 'team\n' > .claude/commands/commit.md \
  && git add -A && git commit -qm base) || die setup "git"
mv "$P/CLAUDE.md" "$P/CLAUDE.md.bak" && ln -s AGENTS.md "$P/CLAUDE.md"
printf '# Dev Workflow — Agent Guide\n\nv1 rules\n' > "$P/AGENTS.md"
printf -- '---\ndescription: plan\n%s\n---\nbody\n' "$MARK" > "$P/.claude/commands/plan.md"
printf -- '---\n%s\n---\nshared\n' "$MARK" > "$P/.claude/commands/_shared/tracker.md"
printf -- '---\nname: mine\n---\nmine\n' > "$P/.claude/skills/mine/SKILL.md"
printf '#!/usr/bin/env bash\n# PreToolUse hook for Bash — block the irreversible.\n' > "$P/.claude/hooks/guard-bash.sh"
printf '#!/usr/bin/env bash\n# my own hook\n' > "$P/.claude/hooks/custom.sh"
printf '#!/usr/bin/env bash\n# Read one value from config.env without ever showing the rest of the file.\n' > "$P/.claude/tools/cfg.sh"
cat > "$P/.claude/settings.json" <<'EOF'
{"permissions":{"allow":["Bash(make *)","Bash(.claude/tools/cfg.sh:*)"]},
 "statusLine":{"type":"command","command":"\"$CLAUDE_PROJECT_DIR/.claude/hooks/statusline.sh\""},
 "hooks":{"PreToolUse":[{"matcher":"Bash","hooks":[{"type":"command","command":"\"$CLAUDE_PROJECT_DIR/.claude/hooks/guard-bash.sh\""}]}],
          "Notification":[{"matcher":"","hooks":[{"type":"command","command":"cmux notify"}]}]}}
EOF
printf '\n# Solo Dev Workflow — never commit these\nconfig.env\nAGENTS.md\n' >> "$P/.git/info/exclude"
printf 'JIRA_BASE_URL="tracker.invalid/"\nexport JIRA_EMAIL=me@test.invalid\nJIRA_TOKEN=supersecret123\n' > "$P/config.env"

# Project 2: a non-git workspace parent holding one repo; untracked CLAUDE.md symlink + .bak.
W="$tmp/work space"
mkdir -p "$W/.claude/commands" "$W/app"
(cd "$W/app" && git init -q . && git commit -q --allow-empty -m base) || die setup "git"
printf 'MY NOTES\n' > "$W/CLAUDE.md.bak"; ln -s AGENTS.md "$W/CLAUDE.md"; printf 'team agents\n' > "$W/AGENTS.md"
printf -- '---\n%s\n---\nx\n' "$MARK" > "$W/.claude/commands/ship.md"
printf '# Solo Dev Workflow — never commit these\n.claude/\n' >> "$W/app/.git/info/exclude"

before_p=$(tree_sum "$P"); before_w=$(tree_sum "$W"); before_h=$(tree_sum "$HOME")
B --migrate "$P" --dry-run > "$tmp/d1" 2>&1; rc=$?
expect_rc dry-run 1 "$rc"
B --migrate "$W" --dry-run > "$tmp/d2" 2>&1; rc=$?
expect_rc dry-run 0 "$rc"
[ "$(tree_sum "$P")" = "$before_p" ] || die dry-run "project 1 changed"
[ "$(tree_sum "$W")" = "$before_w" ] || die dry-run "project 2 changed"
[ "$(tree_sum "$HOME")" = "$before_h" ] || die dry-run "HOME changed"
[ ! -s "$BINLOG" ] || die dry-run "ran $(cat "$BINLOG")"
has dry-run "(dry-run) remove" "$tmp/d1"
has dry-run "git checkout -- CLAUDE.md" "$tmp/d1"
ok "--migrate --dry-run prints actions and changes nothing"

B --migrate "$P" > "$tmp/o1" 2>&1; rc=$?
expect_rc migrate 1 "$rc"
has deferred "deferred for $P: the v1 block hides config.env" "$tmp/o1"
grep -q '^sdw-exclude' "$BINLOG" && die deferred "exclude block changed while config.env exists"
hasnt secret "supersecret123" "$tmp/o1"
hasnt secret "supersecret123" "$tmp/d1"
has keychain "security add-generic-password -U -s sdw:jira:tracker.invalid -a me@test.invalid -w" "$tmp/o1"
ok "token never printed; Keychain one-liner ends in a bare -w"

[ ! -e "$P/.claude/commands/plan.md" ] && [ ! -e "$P/.claude/commands/_shared" ] || die generated "marked files left"
[ -f "$P/.claude/commands/commit.md" ] && [ -f "$P/.claude/skills/mine/SKILL.md" ] || die generated "unmarked files removed"
[ ! -e "$P/.claude/hooks/guard-bash.sh" ] && [ -f "$P/.claude/hooks/custom.sh" ] || die generated "hook selection wrong"
[ ! -e "$P/.claude/tools" ] || die generated "empty tools dir left"
has generated "not generated by v1, kept: .claude/skills/mine/SKILL.md" "$tmp/o1"
ok "only v1-generated files removed; the rest listed"

jtrue settings '(.hooks.PreToolUse // null) == null and .hooks.Notification[0].hooks[0].command == "cmux notify"' "$P/.claude/settings.json"
jtrue settings '(has("statusLine") | not) and .permissions.allow == ["Bash(make *)"]' "$P/.claude/settings.json"
bk=$(ls -d "$HOME/.local/share/sdw/backups/client repo-"* | head -1)
[ -f "$bk/.claude/settings.json" ] && [ -f "$bk/AGENTS.md" ] || die backup "backups missing under HOME"
ok "legacy hook wiring removed, user entries kept, backups outside the project"

[ ! -L "$P/CLAUDE.md" ] && [ "$(cat "$P/CLAUDE.md")" = "TEAM RULES" ] || die claude-md "tracked CLAUDE.md not restored"
[ ! -e "$P/AGENTS.md" ] || die claude-md "v1 AGENTS.md left"
[ ! -e "$P/CLAUDE.md.bak" ] || die claude-md "identical CLAUDE.md.bak left"
rm "$P/config.env"; before_p=$(tree_sum "$P")
B --migrate "$P" > "$tmp/o1b" 2>&1; rc=$?
expect_rc rerun 0 "$rc"
[ "$(tree_sum "$P")" = "$before_p" ] || die rerun "second migrate changed files"
has exclude "sdw-exclude|$P|--legacy $P" "$BINLOG"
has doctor "sdw-doctor|$P|" "$BINLOG"
ok "CLAUDE.md restored from git; exclude migrated only once config.env is gone; rerun is a no-op"

: > "$BINLOG"
B --migrate "$W" > "$tmp/o2" 2>&1; rc=$?
expect_rc workspace 0 "$rc"
[ ! -L "$W/CLAUDE.md" ] && [ "$(cat "$W/CLAUDE.md")" = "MY NOTES" ] || die workspace "CLAUDE.md.bak not restored"
[ "$(cat "$W/AGENTS.md")" = "team agents" ] || die workspace "team AGENTS.md touched"
[ ! -e "$W/.claude/commands/ship.md" ] || die workspace "marked file left"
has workspace "sdw-exclude|$W/app|--legacy $W/app" "$BINLOG"
ok "workspace parent: .bak restored, child repo exclude migrated"

T="$tmp/tracked"
mkdir -p "$T/.claude"
cp "$P/.claude/settings.json" "$T/.claude/settings.json"
jq '.hooks.Stop = [{"hooks":[{"type":"command","command":".claude/hooks/stop-gate.sh"}]}]' "$T/.claude/settings.json" > "$T/s" && mv "$T/s" "$T/.claude/settings.json"
(cd "$T" && git init -q . && git add -A && git commit -qm base) || die setup "git"
cp "$T/.claude/settings.json" "$tmp/tracked.orig"
B --migrate "$T" > "$tmp/o3" 2>&1; rc=$?
expect_rc tracked 0 "$rc"
cmp -s "$T/.claude/settings.json" "$tmp/tracked.orig" || die tracked "tracked settings.json was edited"
has tracked "tracked by the repo" "$tmp/o3"
has tracked ".claude/hooks/stop-gate.sh" "$tmp/o3"
ok "tracked settings.json: entries printed, file untouched"
