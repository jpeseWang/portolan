#!/usr/bin/env bash
# post-edit: QA phase flips to execute when sdw:qa writes cases.md; formatter only when the repo declares one.
. "$(dirname "$0")/_lib.sh"

W="$tmp/ws"
mkdir -p "$W/.sdw/work/feat"
mkrepo "$W/app" feat
echo design > "$W/.sdw/work/feat/.qa-phase"
touch "$W/.sdw/work/feat/cases.md" "$W/.sdw/work/feat/notes.md"
edit() { hook_json post-edit.sh "{\"cwd\":$(json_str "$W/app"),\"session_id\":\"s1\",\"agent_type\":$(json_str "$1"),\"tool_input\":{\"file_path\":$(json_str "$2")}}"; }

edit sdw:qa "$W/.sdw/work/feat/notes.md"
[ "$(cat "$W/.sdw/work/feat/.qa-phase")" = design ] || fail "other file" "phase changed"; ok "other work file keeps design"
edit "" "$W/.sdw/work/feat/cases.md"
[ "$(cat "$W/.sdw/work/feat/.qa-phase")" = design ] || fail "main session" "phase changed"; ok "main session writing cases.md keeps design"
F="$W/.sdw/work/feat"
printf '| ID | Given/When/Then | Source | Status | Evidence |\n|---|---|---|---|---|\n| AC-1 | x | ticket AC | TODO | |\n| AC-2 | y | ticket AC | TODO | |\n' > "$F/plan.md"
echo stub > "$F/cases.md"
edit sdw:qa "$F/cases.md"
[ "$(cat "$F/.qa-phase")" = design ] || fail "stub" "a stub cases.md ended the design phase"; ok "stub cases.md keeps design"
printf '| ID | Source |\n|---|---|\n| TC-01 | AC-1 |\n| TC-02 | AC-12 |\n' > "$F/cases.md"
edit sdw:qa "$F/cases.md"
[ "$(cat "$F/.qa-phase")" = design ] || fail "missing AC" "flipped without a case for AC-2"; ok "an AC without a case keeps design"
printf '| ID | Source |\n|---|---|\n| TC-01 | AC-1 |\n| TC-02 | AC-2, spec 4 |\n' > "$F/cases.md"
edit sdw:qa "$F/cases.md"
[ "$RC" = 0 ] && [ "$(cat "$F/.qa-phase")" = execute ] || fail "flip" "$(cat "$F/.qa-phase")"
cmp -s "$F/cases.md" "$F/.cases.design.md" || fail "snapshot" "no design snapshot"
ok "complete cases.md flips to execute and keeps a design snapshot"
echo changed >> "$F/cases.md"
edit sdw:qa "$F/cases.md"
cmp -s "$F/cases.md" "$F/.cases.design.md" && fail "snapshot" "snapshot rewritten in execute"
ok "snapshot not rewritten after design"

# Formatter: fake prettier in node_modules/.bin that marks the file.
mkdir -p "$W/app/node_modules/.bin"
printf '#!/bin/sh\nfor a in "$@"; do case "$a" in --check) grep -q ugly && exit 1; exit 0 ;; esac; done\nfor a in "$@"; do last=$a; done\necho formatted >> "$last"\n' > "$W/app/node_modules/.bin/prettier"
chmod +x "$W/app/node_modules/.bin/prettier"
echo 'x' > "$W/app/src/new.ts"
edit "" "$W/app/src/new.ts"
grep -q formatted "$W/app/src/new.ts" && fail "no config" "formatted without a prettier config"
ok "no prettier config: untouched"
echo '{}' > "$W/app/.prettierrc"
edit "" "$W/app/src/new.ts"
grep -q formatted "$W/app/src/new.ts" || fail "config" "not formatted"
ok "prettier config + local binary: formatted"
(cd "$W/app" && echo ugly > src/legacy.ts && git add src/legacy.ts && git commit -qm legacy) || fail setup legacy
echo 'ugly edit' > "$W/app/src/legacy.ts"
edit "" "$W/app/src/legacy.ts"
grep -q formatted "$W/app/src/legacy.ts" && fail "legacy" "unformatted HEAD file was reformatted"
ok "tracked file unformatted at HEAD: left alone"
echo '# t' > "$W/app/src/doc.md"
edit "" "$W/app/src/doc.md"
grep -q formatted "$W/app/src/doc.md" && fail "md" "markdown formatted"
ok "markdown never formatted"
echo y > "$W/app/src/q.ts"
edit sdw:qa "$W/app/src/q.ts"
grep -q formatted "$W/app/src/q.ts" && fail "agent" "formatted for sdw agent"
ok "sdw agent edits not formatted"
printf '#!/bin/sh\nexit 1\n' > "$tmp/stub/jq"; chmod +x "$tmp/stub/jq"
edit "" "/nonexistent/file.ts"
[ "$RC" = 0 ] || fail "always 0" "$RC"; ok "post-edit always exits 0"
